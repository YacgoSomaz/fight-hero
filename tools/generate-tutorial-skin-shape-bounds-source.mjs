import fs from 'node:fs';
import { extractUnitMCSkinBaseShapeBounds } from '../private-assets/parse-unitmc-skin-graph.mjs';
import { createCampaignOneSession } from '../src/campaign-one-session.mjs';
import { createTutorialActorBindings } from '../src/tutorial-actor-bindings.mjs';

const skinFrames = [...new Set(createTutorialActorBindings(createCampaignOneSession()).actors.map(({ skinFrame }) => skinFrame))]
  .sort((left, right) => left - right);
const sourceBounds = Object.fromEntries(skinFrames.map((skinFrame) => [skinFrame, Object.fromEntries(
  extractUnitMCSkinBaseShapeBounds(skinFrame).map(({ path, bounds }) => [path, bounds]),
)]));
const body = `// Generated by tools/generate-tutorial-skin-shape-bounds-source.mjs from direct original UnitMC Shape RECTs.\nexport const SOURCE_TUTORIAL_SKIN_SHAPE_BOUNDS = ${JSON.stringify(sourceBounds, null, 2)};\n\nexport function tutorialSkinShapeBounds(path, skinFrame) {\n  const bounds = SOURCE_TUTORIAL_SKIN_SHAPE_BOUNDS[skinFrame]?.[path];\n  if (!bounds) throw new Error(\`UnitMC base Shape crop \${path}/\${skinFrame} was not exported\`);\n  return bounds;\n}\n`;
fs.writeFileSync('src/tutorial-skin-shape-bounds-source.mjs', body);
console.log(`wrote ${skinFrames.length} UnitMC base-Shape crop-origin maps`);
