import fs from 'node:fs';
import { extractUnitMCSkinFrameBounds } from '../private-assets/parse-unitmc-skin-graph.mjs';
import { createCampaignOneSession } from '../src/campaign-one-session.mjs';
import { createTutorialActorBindings } from '../src/tutorial-actor-bindings.mjs';

const skinFrames = [...new Set(createTutorialActorBindings(createCampaignOneSession()).actors.map(({ skinFrame }) => skinFrame))]
  .sort((left, right) => left - right);
const sourceBounds = Object.fromEntries(skinFrames.map((skinFrame) => [skinFrame, Object.fromEntries(
  extractUnitMCSkinFrameBounds(skinFrame).map(({ character, bounds }) => [character, bounds]),
)]));
const body = `// Generated by tools/generate-tutorial-skin-bounds-source.mjs from original UnitMC nested Sprite bounds.\nexport const SOURCE_UNITMC_SKIN_BOUNDS = ${JSON.stringify(sourceBounds, null, 2)};\n\nexport function tutorialSkinBounds(character, skinFrame) {\n  const bounds = SOURCE_UNITMC_SKIN_BOUNDS[skinFrame]?.[character];\n  if (!bounds) throw new Error(\`Character \${character} at skin frame \${skinFrame} is not an exported UnitMC skin child sprite\`);\n  return bounds;\n}\n`;
fs.writeFileSync('src/tutorial-skin-bounds-source.mjs', body);
console.log(`wrote ${skinFrames.length} UnitMC skin-frame registration maps`);
