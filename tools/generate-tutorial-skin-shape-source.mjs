import fs from 'node:fs';
import { createCampaignOneSession } from '../src/campaign-one-session.mjs';
import { createTutorialActorBindings } from '../src/tutorial-actor-bindings.mjs';
import { extractUnitMCSkinFrameLayers } from '../private-assets/parse-unitmc-skin-graph.mjs';

const skinFrames = [...new Set(createTutorialActorBindings(createCampaignOneSession()).actors.map(({ skinFrame }) => skinFrame))]
  .sort((left, right) => left - right);
const source = Object.fromEntries(skinFrames.map((skinFrame) => [skinFrame, Object.fromEntries(
  extractUnitMCSkinFrameLayers(skinFrame).map(({ path, items }) => {
    const shape = items.find(({ name }) => !name);
    if (!shape) throw new Error(`UnitMC skin ${path}/${skinFrame} has no direct base Shape`);
    return [path, { character: shape.character, source: `./public/assets/original-swf/unit-skin-shapes/${shape.character}.png` }];
  }),
)]));
const body = `// Generated by tools/generate-tutorial-skin-shape-source.mjs from UnitMC nested display lists.\n// The selected Shape excludes separately controlled child layers such as legup2.gun.\nexport const SOURCE_TUTORIAL_SKIN_SHAPES = ${JSON.stringify(source, null, 2)};\n\nexport function tutorialSkinShape(path, skinFrame) {\n  const shape = SOURCE_TUTORIAL_SKIN_SHAPES[skinFrame]?.[path];\n  if (!shape) throw new Error(\`UnitMC skin Shape \${path}/\${skinFrame} was not exported\`);\n  return shape;\n}\n\nexport function tutorialSkinShapeAssetPath(path, skinFrame) {\n  return tutorialSkinShape(path, skinFrame).source;\n}\n`;
fs.writeFileSync('src/tutorial-skin-shape-source.mjs', body);
console.log(`wrote ${skinFrames.length} UnitMC base-Shape source maps`);
